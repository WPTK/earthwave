"""Regenerate earthwave/iasp91_table.py from obspy.taup (dev-only: `pip install obspy`).

    python scripts/gen_iasp91_table.py

P is the earliest arrival of any phase. That includes Pdiff, which IASP91 carries to 156-158.5 degrees (depth
dependent) before the first arrival jumps ~115 s to PKIKP; the extra nodes around 154-160 keep the jump to one cell.
S is the earliest S-type arrival: S, s, Sn, Sg, Sdiff, SKS, SKIKS
(the S-wave through the outer core, past the S shadow beyond ~104 degrees). Core-converted PKS and PKIKS are left
out: they are P in the mantle, arrive earlier than SKS from ~110 degrees, and are not what a seismometer calls S.
A cell with no S arrival at all is filled with P * VP_VS, the crustal Vp/Vs ratio.
"""

from pathlib import Path

from obspy.taup import TauPyModel

DISTANCES_DEG = (
    0, 0.25, 0.5, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 12, 14, 16, 18, 20, 23, 26, 30, 35, 40, 45, 50, 60, 70, 80, 90, 100,
    105, 110, 120, 130, 140, 150, 154, 156, 157, 158, 158.5, 159, 160, 165, 170, 180,
)  # fmt: skip
DEPTHS_KM = (0, 5, 10, 20, 35, 50, 70, 100, 150, 200, 300, 400, 500, 600, 700)
S_PHASES = ["s", "S", "Sn", "Sg", "Sdiff", "SKS", "SKIKS"]
VP_VS = 1.75
OUT = Path(__file__).resolve().parents[1] / "earthwave" / "iasp91_table.py"


def first(model: TauPyModel, depth: float, deg: float, phases: list[str] | None) -> float | None:
    kwargs = {"phase_list": phases} if phases else {}
    arrivals = model.get_travel_times(depth, deg, **kwargs)
    return min((float(a.time) for a in arrivals), default=None)


def main() -> None:
    model = TauPyModel("iasp91")
    p_rows, s_rows = [], []
    for depth in DEPTHS_KM:
        p_row = [first(model, depth, deg, None) for deg in DISTANCES_DEG]
        s_row = [first(model, depth, deg, S_PHASES) for deg in DISTANCES_DEG]
        p_rows.append([round(t, 1) for t in p_row])
        s_rows.append([round(s if s is not None else p * VP_VS, 1) for p, s in zip(p_row, s_row, strict=True)])
    lines = [
        '"""IASP91 first-arrival P and S travel times in seconds, '
        'generated by scripts/gen_iasp91_table.py. Do not edit."""',
        "",
        f"DISTANCES_DEG = {DISTANCES_DEG!r}",
        f"DEPTHS_KM = {DEPTHS_KM!r}",
        "# One row per depth, one column per distance.",
    ]
    for name, rows in (("P_SECONDS", p_rows), ("S_SECONDS", s_rows)):
        lines.append(f"{name} = (")
        lines.extend(f"    {tuple(row)!r}," for row in rows)
        lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
